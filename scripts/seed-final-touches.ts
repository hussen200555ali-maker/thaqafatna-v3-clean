async function main() {
  console.log("إكمال مكتبة الموجة الثانية + إثراء المجتمع…\n");

  /* ---------- فصول الكتابين ---------- */
  for (const entry of FILL_CHAPTERS) {
    const book = await db.book.findFirst({ where: { title: entry.bookTitle } });
    if (!book) {
      console.log(`  ! كتاب «${entry.bookTitle}» غير موجود — تخطٍّ`);
      continue;
    }
    const existing = await db.bookChapter.findMany({
      where: { bookId: book.id },
      select: { title: true },
    });
    const titles = new Set(existing.map((c) => c.title));
    for (const chapter of entry.chapters) {
      if (titles.has(chapter.title)) continue;
      await db.bookChapter.create({
        data: {
          bookId: book.id,
          title: chapter.title,
          order: chapter.order,
          content: chapter.content,
        },
      });
      console.log(`  + «${entry.bookTitle}» — فصل: ${chapter.title}`);
    }
  }

  /* ---------- لاعبون جدد ---------- */
  for (const player of NEW_PLAYERS) {
    const existing = await db.playerProfile.findUnique({
      where: { deviceId: player.deviceId },
    });
    if (existing) {
      console.log(`  ~ اللاعب «${player.name}» موجود مسبقاً`);
      continue;
    }
    await db.playerProfile.create({ data: player });
    console.log(`  + لاعب: ${player.name} (${player.points} نقطة)`);
  }

  /* ---------- تقرير التحقق ---------- */
  const books = await db.book.findMany({
    orderBy: { order: "asc" },
    include: { _count: { select: { chapters: true } } },
  });
  const empty = books.filter((b) => b._count.chapters === 0);
  console.log(
    `\nالمكتبة: ${books.length} كتباً، بلا فصول: ${empty.length === 0 ? "لا شيء — كل الكتب مسلولة" : empty.map((b) => b.title).join("، ")}`,
  );
  const players = await db.playerProfile.count();
  console.log(`الصدارة: ${players} لاعباً.`);
}

main()
  .catch((error) => {
    console.error("فشل البذر:", error);
    process.exitCode = 1;
  })
  .finally(() => db.$disconnect());
