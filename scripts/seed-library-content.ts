async function main() {
  console.log("بذر محتوى المكتبة العامة — نصوص الفصول والمراجعات…");

  /* 1) محتوى الفصول — للفصول الفارغة فقط */
  const chapters = await db.bookChapter.findMany();
  let filled = 0;
  for (const chapter of chapters) {
    const content = chapterContents[chapter.title];
    if (content && !chapter.content) {
      await db.bookChapter.update({
        where: { id: chapter.id },
        data: { content },
      });
      filled += 1;
    }
  }
  console.log(`مُلئ محتوى ${filled} فصلاً من أصل ${chapters.length}.`);

  /* 2) المراجعات — مرة واحدة عند فراغ الجدول */
  const reviewCount = await db.bookReview.count();
  if (reviewCount > 0) {
    console.log(`المراجعات موجودة مسبقاً (${reviewCount}) — لا حاجة للتكرار.`);
    return;
  }

  const books = await db.book.findMany({ select: { id: true, title: true } });
  const byTitle = new Map(books.map((book) => [book.title, book.id]));

  let seeded = 0;
  for (const seed of reviewSeeds) {
    const bookId = byTitle.get(seed.bookTitle);
    if (!bookId) continue;
    await db.bookReview.create({
      data: {
        bookId,
        author: seed.author,
        rating: seed.rating,
        comment: seed.comment,
        status: seed.status,
      },
    });
    seeded += 1;
  }
  console.log(`بُذرت ${seeded} مراجعة (معتمدة ومعلّقة).`);
}

main()
  .catch((error) => {
    console.error("فشل البذر:", error);
    process.exitCode = 1;
  })
  .finally(() => db.$disconnect());
