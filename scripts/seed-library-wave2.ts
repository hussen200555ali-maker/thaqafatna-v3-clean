async function main() {
  console.log("بذر مكتبة الموجة الثانية — ٤ كتب جديدة…\n");

  for (const book of BOOKS) {
    /* التصنيف — يجب أن يكون موجوداً من بذر الفهرس الأول */
    const category = await db.bookCategory.findFirst({
      where: { title: book.categoryTitle },
    });
    if (!category) {
      console.log(`  ! تصنيف «${book.categoryTitle}» غير موجود — تخطّي «${book.title}»`);
      continue;
    }

    /* الكتاب — إن لم يوجد */
    let record = await db.book.findFirst({ where: { title: book.title } });
    if (!record) {
      record = await db.book.create({
        data: {
          title: book.title,
          author: book.author,
          description: book.description,
          status: "published",
          categoryId: category.id,
          order: book.order,
        },
      });
      console.log(`  + كتاب: ${book.title} (${book.categoryTitle})`);
    } else {
      console.log(`  ~ كتاب «${book.title}» موجود مسبقاً`);
    }

    /* الفصول — لكل كتابٍ ما لم يُزرع */
    const existingChapters = await db.bookChapter.findMany({
      where: { bookId: record.id },
      select: { title: true },
    });
    const existingTitles = new Set(existingChapters.map((c) => c.title));
    for (const chapter of book.chapters) {
      if (existingTitles.has(chapter.title)) continue;
      await db.bookChapter.create({
        data: {
          bookId: record.id,
          title: chapter.title,
          order: chapter.order,
          content: chapter.content,
        },
      });
      console.log(`    + فصل: ${chapter.title}`);
    }
  }

  /* ---------- مقامات الحريري — فصول المسودة ---------- */
  const hariri = await db.book.findFirst({ where: { title: "مقامات الحريري" } });
  if (hariri) {
    const existing = await db.bookChapter.findMany({
      where: { bookId: hariri.id },
      select: { title: true },
    });
    const titles = new Set(existing.map((c) => c.title));
    for (const chapter of HARIRI_CHAPTERS) {
      if (titles.has(chapter.title)) continue;
      await db.bookChapter.create({
        data: {
          bookId: hariri.id,
          title: chapter.title,
          order: chapter.order,
          content: chapter.content,
        },
      });
      console.log(`  + مقامات الحريري — فصل: ${chapter.title}`);
    }
  } else {
    console.log("  ! مقامات الحريري غير موجودة في الفهرس");
  }

  /* ---------- المراجعات ---------- */
  if ((await db.bookReview.count()) >= 12) {
    console.log("\n  ~ المراجعات مزروعة مسبقاً — تخطٍّ");
  } else {
    for (const review of NEW_REVIEWS) {
      const book = await db.book.findFirst({ where: { title: review.bookTitle } });
      if (!book) continue;
      await db.bookReview.create({
        data: {
          bookId: book.id,
          author: review.author,
          rating: review.rating,
          comment: review.comment,
          status: review.status,
        },
      });
      console.log(`  + مراجعة (${review.status === "approved" ? "معتمدة" : "معلّقة"}): ${review.bookTitle}`);
    }
  }

  /* ---------- تقرير التحقق ---------- */
  const books = await db.book.findMany({
    orderBy: { order: "asc" },
    include: { _count: { select: { chapters: true, reviews: true } } },
  });
  console.log("\n=== رفوف المكتبة النهائية ===");
  for (const book of books) {
    console.log(
      `${book.order}) «${book.title}» [${book.status === "published" ? "منشور" : "مسودة"}] — ${book._count.chapters} فصول — ${book._count.reviews} مراجعات — ${book.author?.split("—")[0]?.trim() ?? "مجهول"}`,
    );
  }
}

main()
  .catch((error) => {
    console.error("فشل البذر:", error);
    process.exitCode = 1;
  })
  .finally(() => db.$disconnect());
