/**
 * أدوات تطبيع الإجابات العربية (Answer Normalization Utils)
 * ===========================================================
 * الطبقة الدفاعية بين «ما يكتبه اللاعب» و«ما حفظته لوحة الإدارة».
 *
 * لماذا نطبّع؟ لوحة الإدارة قد تحفظ «أَحْمَد» مشكولةً واللاعب يكتب
 * «احمد» خالية من الشكل — كلاهما الإجابة نفسها. العقاب على الشكل
 * الإملائي في لعبة ثقافية = إحباط بلا قيمة تعليمية.
 *
 * سياسة التطبيع (متساهلة عمداً كالتقاليد المتبعة في ألعاب الكلمات):
 *   • حذف التشكيل والشدّة والتطويل
 *   • توحيد الألف بأشكالها (أ إ آ ٱ ← ا)
 *   • توحيد الهمزات (ؤ ← و، ئ ← ي) والألف المقصورة (ى ← ي)
 *   • التاء المربوطة تعادل الهاء (ة ← ه)
 *   • حذف علامات الترقيم وتوحيد المسافات
 *
 * ملاحظة: التحقق الصارم حرفاً-حرفاً (الحروف المبعثرة والشبكة)
 * يبقى كما هو في وحداته — التطبيع هنا للإجابات «المكتوبة» فقط.
 */

/** نطاقات التشكيل والعلامات القرآنية في يونيكود */
const DIACRITICS = /[\u064B-\u065F\u0670\u06D6-\u06ED]/g;
/** حرف التطويل (الكشيدة) */
const TATWEEL = /\u0640/g;
/** علامات ترقيم شائعة — تُهمل عند المقارنة */
const PUNCTUATION = /[.,،؛:؟!()[\]{}«»"'\-–—_/\\]/g;

/** تطبيع نص عربي للمقارنة العادلة */
export function normalizeArabic(text: string): string {
  return text
    .replace(DIACRITICS, "")
    .replace(TATWEEL, "")
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/ؤ/g, "و")
    .replace(/ئ/g, "ي")
    .replace(/ة/g, "ه")
    .replace(PUNCTUATION, " ")
    .replace(/\s+/g, " ")
    .trim();
}

/** هل تطابق إجابة اللاعب الإجابة المحفوظة (بعد التطبيع)؟ */
export function arabicAnswersMatch(input: string, expected: string): boolean {
  return normalizeArabic(input) === normalizeArabic(expected);
}

/** عدد الأحرف الفعلية (بلا مسافات ولا تشكيل) — لمساعدات طول الإجابة */
export function countArabicLetters(text: string): number {
  return normalizeArabic(text).replace(/\s/g, "").length;
}
